export const isReservedWord = (dialect: Dialect, word: string): boolean =>
  RESERVED[dialect].has(word.toUpperCase());

/**
 * The identifier as it must be typed: bare when it can be (a plain name that is not a
 * reserved word, all lower case in PostgreSQL, which folds unquoted names), else quoted
 * with `quoteIdent`.
 */
export function quoteIdentIfNeeded(dialect: Dialect, name: string): string {
  const plain = dialect === "postgres" ? /^[a-z_][a-z0-9_]*$/ : /^[A-Za-z_][A-Za-z0-9_]*$/;
  return plain.test(name) && !isReservedWord(dialect, name) ? name : quoteIdent(dialect, name);
}
