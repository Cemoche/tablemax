//! Shared helpers for the database integration tests (PostgreSQL, MySQL/MariaDB).
#![allow(dead_code)]

use tablemax_lib::driver::tls::{SslConfig, SslMode, install_crypto_provider};
use tablemax_lib::driver::{ConnectParams, DriverKind};

fn urls_from_env(var: &str) -> Vec<String> {
    let raw = std::env::var(var).unwrap_or_else(|_| {
        panic!("{var} is not set: run `pnpm test:rust` (scripts/test-dbs.sh up)")
    });
    let urls: Vec<String> = raw
        .split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(String::from)
        .collect();
    assert!(
        !urls.is_empty(),
        "{var} is empty: run `pnpm test:rust` (scripts/test-dbs.sh up)"
    );
    urls
}

pub fn pg_urls() -> Vec<String> {
    urls_from_env("TABLEMAX_TEST_PG_URLS")
}

pub fn mysql_urls() -> Vec<String> {
    urls_from_env("TABLEMAX_TEST_MYSQL_URLS")
}

/// Parses `scheme://user:pass@host:port/db` into connect params (default TLS: `Prefer`).
/// Also installs the rustls crypto provider, as the app does at startup: every
/// integration test builds its params here.
pub fn params_from_url(url: &str, kind: DriverKind) -> ConnectParams {
    install_crypto_provider();
    let u = url::Url::parse(url).unwrap_or_else(|e| panic!("bad test url {url}: {e}"));
    let decode = percent_decode;
    let db = u.path().trim_start_matches('/');
    ConnectParams {
        kind,
        host: u.host_str().expect("url host").to_string(),
        port: u.port().expect("url port"),
        user: decode(u.username()),
        password: u.password().map(decode),
        database: if db.is_empty() {
            None
        } else {
            Some(decode(db))
        },
        sqlite_path: None,
        ssl: SslConfig::default(),
        dial: None,
    }
}

/// Absolute path of a file generated by `scripts/test-secrets.sh` (ca.pem, foreign-ca.pem,
/// client.pem, client.key...).
pub fn tls_file(name: &str) -> String {
    let dir = std::env::var("TABLEMAX_TEST_TLS_DIR").unwrap_or_else(|_| {
        panic!("TABLEMAX_TEST_TLS_DIR is not set: run `pnpm test:rust` (scripts/test-dbs.sh up)")
    });
    format!("{dir}/{name}")
}

/// TLS settings with an optional CA from the test material.
pub fn ssl(mode: SslMode, ca: Option<&str>) -> SslConfig {
    SslConfig {
        mode,
        ca_file: ca.map(tls_file),
        ..Default::default()
    }
}

/// `host:port` of the test sshd (`TABLEMAX_TEST_SSH`, e.g. `127.0.0.1:2222`).
pub fn ssh_addr() -> (String, u16) {
    let raw = std::env::var("TABLEMAX_TEST_SSH").unwrap_or_else(|_| {
        panic!("TABLEMAX_TEST_SSH is not set: run `pnpm test:rust` (scripts/test-dbs.sh up)")
    });
    let (host, port) = raw
        .rsplit_once(':')
        .expect("TABLEMAX_TEST_SSH is host:port");
    (
        host.to_string(),
        port.parse().expect("TABLEMAX_TEST_SSH port"),
    )
}

/// Absolute path of an SSH client key generated by `scripts/test-secrets.sh`
/// (id_ed25519, id_ed25519_enc, id_rsa_pem).
pub fn ssh_file(name: &str) -> std::path::PathBuf {
    let dir = std::env::var("TABLEMAX_TEST_SSH_DIR").unwrap_or_else(|_| {
        panic!("TABLEMAX_TEST_SSH_DIR is not set: run `pnpm test:rust` (scripts/test-dbs.sh up)")
    });
    std::path::Path::new(&dir).join(name)
}

fn percent_decode(s: &str) -> String {
    let b = s.as_bytes();
    let mut out = Vec::with_capacity(b.len());
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'%'
            && i + 2 < b.len()
            && let Ok(v) = u8::from_str_radix(&s[i + 1..i + 3], 16)
        {
            out.push(v);
            i += 3;
        } else {
            out.push(b[i]);
            i += 1;
        }
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// A unique schema/database name for one test: `t_<uuid simple>`.
pub fn unique_schema() -> String {
    format!("t_{}", uuid::Uuid::new_v4().simple())
}
